import * as cdk from 'aws-cdk-lib/core';
import * as batch from 'aws-cdk-lib/aws-batch';
import * as cloudwatch from 'aws-cdk-lib/aws-cloudwatch';
import * as cwActions from 'aws-cdk-lib/aws-cloudwatch-actions';
import * as ec2 from 'aws-cdk-lib/aws-ec2';
import * as ecs from 'aws-cdk-lib/aws-ecs';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as logs from 'aws-cdk-lib/aws-logs';
import * as s3 from 'aws-cdk-lib/aws-s3';
import * as sns from 'aws-cdk-lib/aws-sns';
import * as subs from 'aws-cdk-lib/aws-sns-subscriptions';
import { Construct } from 'constructs';
import { RunOrchestration } from './run-orchestration';
import { VariantAnalytics } from './variant-analytics';

export class InfraStack extends cdk.Stack {
  constructor(scope: Construct, id: string, props?: cdk.StackProps) {
    super(scope, id, props);

    // One bucket for pipeline inputs, results, and the Nextflow work directory.
    // No explicit name: CDK generates a unique one, so redeploys never collide.
    const bucket = new s3.Bucket(this, 'PipelineBucket', {
      versioned: true,
      encryption: s3.BucketEncryption.S3_MANAGED,
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      enforceSSL: true,
      // Demo project: `cdk destroy` should leave nothing behind.
      removalPolicy: cdk.RemovalPolicy.DESTROY,
      autoDeleteObjects: true,
      lifecycleRules: [
        // Nextflow scratch files are disposable once a run is done.
        { prefix: 'work/', expiration: cdk.Duration.days(14) },
        { prefix: 'athena-results/', expiration: cdk.Duration.days(7) }, // query output, regenerated by rerunning the query
        { noncurrentVersionExpiration: cdk.Duration.days(7) },
        { abortIncompleteMultipartUploadAfter: cdk.Duration.days(1) },
      ],
    });

    // Public subnets only, no NAT gateway (saves ~$32/month). Compute gets public IPs
    // so it can reach the internet; the security group below blocks all inbound traffic.
    const vpc = new ec2.Vpc(this, 'Vpc', {
      maxAzs: 2,
      natGateways: 0,
      subnetConfiguration: [
        { name: 'public', subnetType: ec2.SubnetType.PUBLIC, cidrMask: 24, mapPublicIpOnLaunch: true },
      ],
    });

    // Flow logs for the VPC: who talked to what, kept 30 days.
    const flowLogGroup = new logs.LogGroup(this, 'VpcFlowLogs', {
      retention: logs.RetentionDays.ONE_MONTH,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });
    vpc.addFlowLog('FlowLog', { destination: ec2.FlowLogDestination.toCloudWatchLogs(flowLogGroup) });

    // No inbound rules; outbound is open (image pulls, S3).
    const computeSg = new ec2.SecurityGroup(this, 'ComputeSecurityGroup', {
      vpc,
      description: 'Batch compute: no inbound, all outbound',
      allowAllOutbound: true,
    });

    // Nextflow stages files with the AWS CLI, and biocontainers images don't ship one, so
    // install the CLI into a self-contained Miniconda on each instance. Nextflow mounts /opt/miniconda into every
    // task container (aws.batch.cliPath = /opt/miniconda/bin/aws). Conda carries its own
    // libraries (the standalone CLI v2 binary failed in containers: no libz.so.1).
    const cliUserData = ec2.UserData.forLinux();
    cliUserData.addCommands(
      'set -euo pipefail',
      'cd /tmp',
      'curl -sSfL https://repo.anaconda.com/miniconda/Miniconda3-latest-Linux-x86_64.sh -o miniconda.sh',
      'bash miniconda.sh -b -f -p /opt/miniconda',
      // pip, not conda install: conda's solver needs >3GB and was OOM-killed on a c5.large.
      '/opt/miniconda/bin/pip install --no-cache-dir awscli',
      '/opt/miniconda/bin/aws --version',
    );
    // Batch only accepts launch-template user data in MIME multipart format.
    const multipartUserData = new ec2.MultipartUserData();
    multipartUserData.addPart(ec2.MultipartBody.fromUserData(cliUserData));
    const launchTemplate = new ec2.LaunchTemplate(this, 'ComputeLaunchTemplate', {
      userData: multipartUserData,
      // Containers are one network hop from the instance. IMDSv2 with a hop limit of 1 stops them reading
      // the instance role's credentials from the metadata service; task containers get their S3 access
      // from the job role through the ECS credentials endpoint instead, which is unaffected.
      requireImdsv2: true,
      httpPutResponseHopLimit: 1,
    });

    // Spot (cheap, interruptible) x86 instances. Scales to zero when idle;
    // maxvCpus caps the worst-case bill.
    const computeEnv = new batch.ManagedEc2EcsComputeEnvironment(this, 'ComputeEnv', {
      vpc,
      vpcSubnets: { subnetType: ec2.SubnetType.PUBLIC },
      securityGroups: [computeSg],
      launchTemplate,
      spot: true,
      allocationStrategy: batch.AllocationStrategy.SPOT_PRICE_CAPACITY_OPTIMIZED,
      instanceClasses: [ec2.InstanceClass.M5, ec2.InstanceClass.C5, ec2.InstanceClass.R5],
      useOptimalInstanceClasses: false,
      minvCpus: 0,
      maxvCpus: 16,
    });

    // CDK points Batch at the template's $Default version, and CloudFormation adds new
    // versions without moving the default, so edits to the template would silently never
    // take effect. Pin to the latest version number instead.
    (computeEnv.node.defaultChild as batch.CfnComputeEnvironment).addPropertyOverride(
      'ComputeResources.LaunchTemplate.Version',
      launchTemplate.versionNumber,
    );

    const jobQueue = new batch.JobQueue(this, 'JobQueue', {
      computeEnvironments: [{ computeEnvironment: computeEnv, order: 1 }],
    });

    // Role the pipeline's containers run as. Nextflow's job definitions point at it
    // (aws.batch.jobRole), and it is what lets tasks read and write the bucket.
    const jobRole = new iam.Role(this, 'JobRole', {
      assumedBy: new iam.ServicePrincipal('ecs-tasks.amazonaws.com'),
      description: 'Nextflow task containers: read/write the pipeline bucket',
    });
    // Task containers read inputs from anywhere in the bucket but write only to the Nextflow work area,
    // so a task cannot overwrite the reference, the truth set or published results.
    bucket.grantRead(jobRole);
    bucket.grantPut(jobRole, 'work/*');
    bucket.grantDelete(jobRole, 'work/*');

    // --- Monitoring ---
    // Batch auto-creates /aws/batch/job outside CloudFormation and never expires it, so
    // we own a separate group instead (Nextflow: aws.batch.logsGroup in conf/awsbatch.config).
    const jobLogs = new logs.LogGroup(this, 'JobLogs', {
      logGroupName: '/giab/batch-jobs',
      retention: logs.RetentionDays.ONE_MONTH,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });

    // Count log lines that look like GATK/Java failures.
    const errorLines = jobLogs.addMetricFilter('ErrorLines', {
      metricNamespace: 'GiabPipeline',
      metricName: 'ErrorLines',
      filterPattern: logs.FilterPattern.anyTerm('ERROR', 'Exception'),
      metricValue: '1',
      defaultValue: 0,
    });

    const alertTopic = new sns.Topic(this, 'AlertTopic', { enforceSSL: true });
    // The email address is not stored in the repo: cdk deploy -c alertEmail=<address>
    const alertEmail = this.node.tryGetContext('alertEmail');
    if (alertEmail) {
      alertTopic.addSubscription(new subs.EmailSubscription(alertEmail));
    }

    const errorAlarm = errorLines
      .metric({ statistic: 'Sum', period: cdk.Duration.minutes(5) })
      .createAlarm(this, 'ErrorLinesAlarm', {
        alarmDescription: 'ERROR/Exception lines in pipeline job logs',
        threshold: 1,
        evaluationPeriods: 1,
        treatMissingData: cloudwatch.TreatMissingData.NOT_BREACHING,
      });
    // Batch publishes job-state metrics per queue (AWS/Batch, no charge); alarm on failures.
    const failedJobAlarm = new cloudwatch.Metric({
      namespace: 'AWS/Batch',
      metricName: 'JobsMovedToFailed',
      dimensionsMap: { JobQueueName: jobQueue.jobQueueName },
      statistic: 'Sum',
      period: cdk.Duration.minutes(5),
    }).createAlarm(this, 'FailedJobAlarm', {
      alarmDescription: 'A Batch job in the pipeline queue failed',
      threshold: 1,
      evaluationPeriods: 1,
      treatMissingData: cloudwatch.TreatMissingData.NOT_BREACHING,
    });
    for (const alarm of [errorAlarm, failedJobAlarm]) {
      alarm.addAlarmAction(new cwActions.SnsAction(alertTopic));
    }

    // --- Nextflow launcher ---
    // Nextflow itself runs here, as a Batch job on Fargate (no instances to manage), instead of on
    // a laptop. It submits the real work to the Spot queue above. Deliberately not Spot: if the
    // process coordinating a run is reclaimed, the whole run stops.
    const launcherEnv = new batch.FargateComputeEnvironment(this, 'LauncherEnv', {
      vpc,
      vpcSubnets: { subnetType: ec2.SubnetType.PUBLIC },
      securityGroups: [computeSg],
      maxvCpus: 4,
    });
    const launcherQueue = new batch.JobQueue(this, 'LauncherQueue', {
      computeEnvironments: [{ computeEnvironment: launcherEnv, order: 1 }],
    });

    // What Nextflow needs from AWS to drive Batch: register job definitions, submit and watch jobs
    // on the worker queue, hand the worker job role to them, and read/write the bucket.
    const launcherRole = new iam.Role(this, 'LauncherRole', {
      assumedBy: new iam.ServicePrincipal('ecs-tasks.amazonaws.com'),
      description: 'Nextflow launcher: submit and watch Batch jobs, read/write the pipeline bucket',
    });
    bucket.grantRead(launcherRole);
    for (const prefix of ['work/*', 'runs/*', 'results/*']) {
      bucket.grantPut(launcherRole, prefix);
    }
    bucket.grantDelete(launcherRole, 'work/*'); // Nextflow cleans up its own work files
    jobRole.grantPassRole(launcherRole);
    const nextflowJobDefinitions =
      `arn:${this.partition}:batch:${this.region}:${this.account}:job-definition/nf-*`;
    // Nextflow tags each job definition it registers (one per container image).
    launcherRole.addToPolicy(new iam.PolicyStatement({
      actions: ['batch:TagResource'],
      resources: [nextflowJobDefinitions],
    }));
    // Nextflow registers one job definition per container image. Only Nextflow's own names, and only
    // for these images; add a pattern here when the pipeline starts using a new registry.
    launcherRole.addToPolicy(new iam.PolicyStatement({
      actions: ['batch:RegisterJobDefinition'],
      resources: [nextflowJobDefinitions],
      conditions: {
        StringLike: {
          // The Python image is pinned by digest (python@sha256:...); the tag form is kept so this can land
          // before or after that change.
          'batch:Image': ['quay.io/biocontainers/*', 'python:3.12.15-slim-bookworm*', 'python@sha256:*'],
        },
      },
    }));
    launcherRole.addToPolicy(new iam.PolicyStatement({
      actions: ['batch:DeregisterJobDefinition'],
      resources: [nextflowJobDefinitions],
    }));
    // Nextflow tags every worker job (process.resourceLabels in conf/awsbatch.config), and the launcher
    // can cancel only jobs carrying that tag. Batch checks TagResource on the new job and also on the
    // queue and job definition named in SubmitJob, so all three are covered; the tag value is fixed.
    const workerTag = { key: 'project', value: 'nextflow-giab' };
    launcherRole.addToPolicy(new iam.PolicyStatement({
      actions: ['batch:TerminateJob'],
      resources: [`arn:${this.partition}:batch:${this.region}:${this.account}:job/*`],
      conditions: { StringEquals: { [`aws:ResourceTag/${workerTag.key}`]: workerTag.value } },
    }));
    launcherRole.addToPolicy(new iam.PolicyStatement({
      actions: ['batch:TagResource'],
      resources: [
        `arn:${this.partition}:batch:${this.region}:${this.account}:job/*`,
        jobQueue.jobQueueArn,
      ],
      conditions: {
        'StringEquals': { [`aws:RequestTag/${workerTag.key}`]: workerTag.value },
        'ForAllValues:StringEquals': { 'aws:TagKeys': [workerTag.key] },
      },
    }));
    launcherRole.addToPolicy(new iam.PolicyStatement({
      actions: ['batch:SubmitJob'],
      resources: [
        jobQueue.jobQueueArn,
        nextflowJobDefinitions, // Nextflow registers its job definitions under names starting "nf-".
      ],
    }));
    launcherRole.addToPolicy(new iam.PolicyStatement({
      actions: [
        'batch:DescribeJobs',
        'batch:ListJobs',
        'batch:DescribeJobDefinitions',
        'batch:DescribeJobQueues',
        'batch:DescribeComputeEnvironments',
      ],
      resources: ['*'], // these actions do not support resource-level scoping
    }));

    // The command is supplied at submit time (scripts/run-on-aws.sh); this default only
    // prints the version. The queue and role names reach Nextflow via the same environment
    // variables conf/awsbatch.config reads on a laptop.
    const launcherJobDef = new batch.EcsJobDefinition(this, 'LauncherJobDef', {
      timeout: cdk.Duration.hours(24),
      container: new batch.EcsFargateContainerDefinition(this, 'LauncherContainer', {
        image: ecs.ContainerImage.fromRegistry('nextflow/nextflow@sha256:19cb0a85d7dfa3b647fdb2326b14b911ccca7cbf4ba5b1449564b1f3b5259307'),  // nextflow/nextflow:26.10.1
        cpu: 1,
        memory: cdk.Size.gibibytes(2),
        assignPublicIp: true,
        jobRole: launcherRole,
        logging: ecs.LogDriver.awsLogs({ logGroup: jobLogs, streamPrefix: 'nextflow-launcher' }),
        command: ['nextflow', '-version'],
        environment: {
          AWS_REGION: this.region,
          NXF_OPTS: '-Xms256m -Xmx1g',
          GIAB_BATCH_QUEUE: jobQueue.jobQueueName,
          GIAB_JOB_ROLE: jobRole.roleArn,
        },
      }),
    });

    // --- Run record and orchestration (see run-orchestration.ts) ---
    const orchestration = new RunOrchestration(this, 'Orchestration', {
      bucket,
      launcherQueue,
      launcherJobDefinition: launcherJobDef,
      alertTopic,
      pipelineRepo: this.node.tryGetContext('pipelineRepo') ?? 'jameswagner/nextflow-giab',
    });

    // --- SQL over every variant of a run (see variant-analytics.ts) ---
    new VariantAnalytics(this, 'Athena', { bucket });

    new cdk.CfnOutput(this, 'BucketName', { value: bucket.bucketName });
    new cdk.CfnOutput(this, 'JobQueueName', { value: jobQueue.jobQueueName });
    new cdk.CfnOutput(this, 'JobRoleArn', { value: jobRole.roleArn });
    new cdk.CfnOutput(this, 'LauncherQueueName', { value: launcherQueue.jobQueueName });
    new cdk.CfnOutput(this, 'LauncherJobDefinitionName', { value: launcherJobDef.jobDefinitionName });
    new cdk.CfnOutput(this, 'RunsTableName', { value: orchestration.table.tableName });
    new cdk.CfnOutput(this, 'RunStateMachineArn', { value: orchestration.stateMachine.stateMachineArn });
  }
}
